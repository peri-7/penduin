"""Experiment B: the arm excitation sequence, checked in the sim and written as a C header.

    python python/excitation.py

The pendulum hangs still and the arm plays a fixed list of actions (one per 10 ms tick). Built from
"doublets": +a for T, -a for 2T, +a for T. A doublet ends with the arm back where it started and at
zero speed, exactly, so a long sequence can't drift. Peak excursion = accel*T^2, peak speed = accel*T.

Writes firmware/stepper_motor/excitation.h and data/excitation_plan.png.
"""
from pathlib import Path

import matplotlib.pyplot as plt
import mujoco
import numpy as np

from env import PenduinEnv

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "firmware" / "stepper_motor" / "excitation.h"
PLOT = ROOT / "data" / "excitation_plan.png"
DT = 0.01
MAX_ACCEL = 200     # rad/s^2 for action = 1, same as env.py and MAX_ACCEL in stepper.h

# (arm acceleration in rad/s^2, T in s), each followed by PAUSE s of rest.
# Excursion and peak speed: 120*0.05^2 = 0.30 rad at 6 rad/s, 50*0.1^2 = 0.50 rad at 5 rad/s,
# 12*0.2^2 = 0.48 rad at 2.4 rad/s, 3*0.3^2 = 0.27 rad at 0.9 rad/s (slow: crosses the VMIN dead band)
PLAN = [(120, 0.05), (-120, 0.05),
        (50, 0.10), (-50, 0.10),
        (12, 0.20), (-12, 0.20),
        (3, 0.30), (-3, 0.30)]
START = 1.0         # s of rest before the first doublet
PAUSE = 3.0         # s of rest after each doublet: the pendulum swings freely

# Safety margins checked in the sim
MAX_THETA = np.radians(45)      # the firmware stops at 90 deg
MAX_SWING = np.radians(120)     # pendulum angle from the bottom: stay far from going over the top


def doublet(accel, T):
    n = round(T / DT)
    a = accel / MAX_ACCEL
    return [a] * n + [-a] * (2 * n) + [a] * n


def build():
    actions = [0.0] * round(START / DT)
    for accel, T in PLAN:
        actions += doublet(accel, T) + [0.0] * round(PAUSE / DT)
    return np.array(actions)


def simulate(actions):
    """Play the actions through PenduinEnv.step, from the pendulum hanging still and the arm at 0."""
    env = PenduinEnv(str(ROOT / "model.xml"))
    env.reset(seed=0)
    env.data.qpos[:] = [0.0, np.pi]     # reset() adds a random tilt; start exactly hanging
    env.data.qvel[:] = 0.0
    mujoco.mj_forward(env.model, env.data)
    env.a_prev = env._read_alpha()

    theta, speed, swing = [], [], []
    for k, act in enumerate(actions):
        _, _, terminated, _, _ = env.step(np.array([act]))
        theta.append(env.data.qpos[0])
        speed.append(env.speed)
        swing.append((env.data.qpos[1] % (2 * np.pi)) - np.pi)   # from the bottom
        if terminated:
            raise SystemExit(f"arm limit reached in the sim at t = {k * DT:.2f} s")
    return np.array(theta), np.array(speed), np.array(swing)


def write_header(actions):
    lines = [
        "// Generated by python/excitation.py, don't edit by hand.",
        "// Experiment B: arm doublets with the pendulum hanging. One action per 10 ms tick, in [-1, 1].",
        "#ifndef EXCITATION_H_",
        "#define EXCITATION_H_",
        "",
        f"#define EXCITATION_N {len(actions)}",
        "",
        "static const float EXCITATION[EXCITATION_N] = {",
    ]
    for i in range(0, len(actions), 10):
        # repr of a Python float always has a '.' or an exponent ("0.0", "0.6"), which C needs
        lines.append("    " + ", ".join(f"{float(a)!r}f" for a in actions[i:i + 10]) + ",")
    lines += ["};", "", "#endif", ""]
    HEADER.write_text("\n".join(lines))


def main():
    actions = build()
    theta, speed, swing = simulate(actions)
    t = np.arange(len(actions)) * DT

    print(f"{len(actions)} ticks ({len(actions) * DT:.1f} s)")
    print(f"max |theta| {np.degrees(np.abs(theta).max()):.1f} deg (limit {np.degrees(MAX_THETA):.0f}), "
          f"max |speed| {np.abs(speed).max():.2f} rad/s, max |accel| {np.abs(actions).max() * MAX_ACCEL:.0f} rad/s^2")
    print(f"max pendulum swing {np.degrees(np.abs(swing).max()):.1f} deg from the bottom "
          f"(limit {np.degrees(MAX_SWING):.0f})")
    print(f"arm at the end: {np.degrees(theta[-1]):.2f} deg, speed {speed[-1]:.3f} rad/s")

    assert np.abs(theta).max() < MAX_THETA, "arm goes too far"
    assert np.abs(swing).max() < MAX_SWING, "pendulum swings too far"

    write_header(actions)
    print(f"wrote {HEADER}")

    fig, axs = plt.subplots(4, 1, figsize=(11, 8), sharex=True)
    axs[0].plot(t, actions * MAX_ACCEL); axs[0].set_ylabel("arm accel\n(rad/s²)")
    axs[1].plot(t, speed); axs[1].set_ylabel("arm speed\n(rad/s)")
    axs[2].plot(t, np.degrees(theta)); axs[2].set_ylabel("θ (deg)")
    axs[3].plot(t, np.degrees(swing)); axs[3].set_ylabel("pendulum from\nbottom (deg)")
    axs[3].set_xlabel("time (s)")
    for ax in axs:
        ax.grid(alpha=0.3)
    fig.suptitle("Experiment B plan, simulated with model.xml")
    fig.tight_layout()
    fig.savefig(PLOT, dpi=90)
    print(f"plot saved to {PLOT}")


if __name__ == "__main__":
    main()
